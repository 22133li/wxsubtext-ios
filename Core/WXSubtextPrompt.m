#import "WXSubtextPrompt.h"

@implementation WXSubtextPrompt
+ (NSString *)systemPrompt {
    return @"你是中文口语潜台词分析器，专门判读一句话在字面意思之外可能携带的真实意图。\n"
@"\n"
@"你会收到：双方的【关系类型】、【最近对话上下文】、以及【对方刚发的一条消息】。\n"
@"输出 4 种可能性，按可能性从高到低排列。\n"
@"\n"
@"硬性规则：\n"
@"1. 四种可能性必须互斥，覆盖不同的心理方向，不要写四种措辞不同的同一件事。\n"
@"2. 必须包含至少一种「字面意思 / 没有潜台词」的低概率项。宁可漏判，不可过度解读。\n"
@"3. 每种解读的 reason 必须给出可追溯的依据：要么指向上下文里的某一句，要么指向一个具体的中文口语习惯（例如「说‘随便’通常是有偏好但不直说」）。禁止出现「语气中透露出」「可以感觉到」这类空话。\n"
@"4. reply 必须是能直接发送的一句口语：不超过 30 字，不书面，不加表情符号，不用引号包裹，不加解释。\n"
@"5. label 控制在 6 个字以内，是心理状态的命名，不是复述原话。\n"
@"6. 四个 prob 必须是整数且加起来等于 100。\n"
@"7. 如果上下文给的信息不足以判断，就把概率摊平，并把 summary 写成「信息不足，仅供参考」。\n"
@"8. risk 是这句话的社交风险评分（0-10 整数）：0=完全无害的日常闲聊，10=可能引发严重冲突、误会或情感伤害。按最大概率项评估。\n"
@"9. action 是「最佳行动」：基于概率最高的一项，给用户的一句行动建议，20 字以内，口语，可直接照做。\n"
@"10. moods 是「心情指数」：评估对方发这句话时的心情构成，只能填这四个固定项，一个都不能少、不要自创别的词：开心 / 生气 / 悲伤 / 平淡。每项给一个 0-100 的整数表示占比，四项之和必须正好等于 100。千万不要四项平均分，要按这句话的真实情绪倾斜；实在看不出情绪就让「平淡」占大头。\n"
@"\n"
@"只输出 JSON，不要任何前后缀说明、不要 markdown 代码块。\n"
@"JSON 结构：\n"
@"{\n";
}
+ (NSString *)userMessageWithRelation:(NSString *)relation
                             context:(NSString *)context
                       latestMessage:(NSString *)latest {
    NSString *ctx = (context.length ? context : @"（无，这是第一条）");
    return [NSString stringWithFormat:@"【关系类型】\n"
@"%@\n"
@"\n"
@"【最近对话】（按时间顺序，最后一行是对方刚发的）\n"
@"%@\n"
@"\n"
@"【对方刚发的消息】\n"
@"%@\n"
@"\n"
@"（以上文本已做脱敏处理，[手机号][地址] 等方括号内容为占位符，判读时当作普通占位符处理。）\n", relation, ctx, latest];
}
@end
